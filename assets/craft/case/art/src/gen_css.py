"""Write ../art.css from placeholders.json. Run after render.py."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PH = json.load(open(os.path.join(HERE, "placeholders.json")))

PROJECTS = {"cc": "contextual-chat", "dr": "deal-room", "wl": "white-label", "ee": "easyeat", "rs": "resonance"}
KINDS = ["cover", "band", "stage", "dark"]

# Focus points. Desktop crops are mostly vertical, so x matters on narrow screens only.
# Values: (desktop, tablet <=1100px, phone <=700px)
POS = {
    "cover": ("50% 40%", "32% 40%", "26% 50%"),
    "band": ("50% 50%", "62% 50%", "68% 50%"),
    "stage": ("50% 50%", "50% 50%", "88% 50%"),
    "dark": ("50% 50%", "70% 50%", "76% 50%"),
}
POS_OVERRIDE = {
    ("ee", "stage"): (None, None, "92% 50%"),
    ("rs", "cover"): (None, None, "30% 50%"),
    ("rs", "stage"): (None, None, "90% 40%"),
    ("cc", "band"): (None, "66% 50%", "67% 50%"),
}


def sel(p, k):
    c = f"cc-art--{PROJECTS[p]}-{k}"
    return f".cc .{c} > .cr-wp-photo"


def main():
    out = ["/* Case-study background art: product scenes built from each project's own stills.",
           "   Generated by src/gen_css.py (scenes in src/build.py, rendered by src/render.py). Do not edit by hand.",
           "   2560 file by default (sections are often taller than 16:9, so it is scaled up); 1440 on small 1x screens. A blurred 48px placeholder sits under each image. */", ""]
    # Contextual Chat has no page stylesheet: give its glass cards an indigo tint that matches the art.
    out.append(", ".join(f".cc-art--contextual-chat-{k}" for k in KINDS) +
               " { --wp-glass: rgba(44, 40, 96, 0.44); --wp-glass-light: rgba(150, 156, 220, 0.28); --wp-glass-strong: rgba(36, 32, 84, 0.64); }")
    wide, tab, phone = [], [], []
    for p in PROJECTS:
        for k in KINDS:
            n = f"{p}-{k}"
            if n not in PH:
                continue
            s = sel(p, k)
            d, t, m = POS[k]
            od, ot, om = POS_OVERRIDE.get((p, k), (None, None, None))
            out.append(f'{s} {{ background-color: #111; background-image: url("./{n}-2560.webp"), url("{PH[n]}"); '
                       f'background-size: cover; background-repeat: no-repeat; background-position: {od or d}; }}')
            wide.append(f'  {s} {{ background-image: url("./{n}-1440.webp"), url("{PH[n]}"); }}')
            tab.append(f"  {s} {{ background-position: {ot or t}; }}")
            phone.append(f"  {s} {{ background-position: {om or m}; }}")
    out += ["", "@media (max-width: 1100px) and (max-resolution: 1.49dppx) {", *wide, "}",
            "@media (max-width: 1100px) {", *tab, "}", "@media (max-width: 700px) {", *phone, "}", ""]
    with open(os.path.join(os.path.dirname(HERE), "art.css"), "w") as f:
        f.write("\n".join(out))
    print("art.css written,", sum(1 for l in out if l.startswith(".cc ")), "rules")


if __name__ == "__main__":
    main()
